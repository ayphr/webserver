import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import * as ts from 'typescript';

const root = new URL('../../', import.meta.url);
const routerUrl = new URL('server/src/api/router.ts', root);
const versionUrl = new URL('server/src/api/version.ts', root);
const outputUrl = new URL('src/lib/api/generated/routes.ts', root);
const checkOnly = process.argv.includes('--check');

export type GeneratedRoute = {
  method: string;
  path: string;
  operationId: string;
};

function parseSource(source: string, fileName: string): ts.SourceFile {
  return ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
}

/** Finds the initializer of a top-level (or nested) `const NAME = ...` declaration. */
function findInitializer(sourceFile: ts.SourceFile, name: string): ts.Expression | null {
  let found: ts.Expression | null = null;
  const visit = (node: ts.Node): void => {
    if (found) return;
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === name) {
      found = node.initializer ?? null;
      return;
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return found;
}

function stringProperty(object: ts.ObjectLiteralExpression, name: string): string | null {
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property)) continue;
    const propertyName = ts.isIdentifier(property.name) || ts.isStringLiteralLike(property.name)
      ? property.name.text
      : null;
    if (propertyName !== name) continue;
    if (ts.isStringLiteralLike(property.initializer)) return property.initializer.text;
  }
  return null;
}

/** Reads `API_VERSION` from the version module without evaluating server code. */
export function readApiVersion(versionSource: string): string {
  const initializer = findInitializer(parseSource(versionSource, 'version.ts'), 'API_VERSION');
  if (!initializer || !ts.isStringLiteralLike(initializer)) {
    throw new Error('Could not read API_VERSION from server/src/api/version.ts');
  }
  return initializer.text;
}

function versionedPath(path: string, version: string): string {
  const unversioned = path === '/api'
    ? '/api'
    : path.startsWith('/api/')
      ? path
      : `/api${path.startsWith('/') ? path : `/${path}`}`;
  return `/api/${version}${unversioned.slice('/api'.length)}`;
}

export function operationId(method: string, path: string): string {
  const parts = path
    .replace(/^\/api\//, '')
    .split('/')
    .flatMap((part) => part.split(/[^A-Za-z0-9]+/).filter(Boolean))
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1));
  return [method.toLowerCase(), ...parts].join('');
}

/**
 * Extracts `{ method, path, ... }` entries from the router's `ROUTES` array
 * using the TypeScript AST. Unlike a regex this ignores comments, string
 * contents and unrelated `method`/`path` object literals elsewhere in the file.
 */
export function extractRoutes(routerSource: string, version: string): GeneratedRoute[] {
  const sourceFile = parseSource(routerSource, 'router.ts');
  const initializer = findInitializer(sourceFile, 'ROUTES');
  if (!initializer || !ts.isArrayLiteralExpression(initializer)) {
    throw new Error('Could not find the ROUTES array in server/src/api/router.ts');
  }

  const routes: GeneratedRoute[] = [];
  for (const element of initializer.elements) {
    if (!ts.isObjectLiteralExpression(element)) {
      throw new Error('ROUTES contains a non-literal entry; the generator cannot resolve it safely');
    }
    const method = stringProperty(element, 'method');
    const path = stringProperty(element, 'path');
    if (!method || !path) {
      throw new Error('Every ROUTES entry must have literal `method` and `path` strings');
    }
    if (!/^[A-Z]+$/.test(method) || !path) {
      throw new Error(`Invalid ROUTES entry: ${method} ${path}`);
    }
    routes.push({
      method,
      path: versionedPath(path, version),
      operationId: operationId(method, path),
    });
  }

  if (routes.length === 0) throw new Error('No routes found in server/src/api/router.ts');
  validateRoutes(routes);
  return routes;
}

/** Rejects collisions before they can silently overwrite an API_PATHS key. */
export function validateRoutes(routes: readonly GeneratedRoute[]): void {
  const seenPaths = new Set<string>();
  const seenOperationIds = new Set<string>();
  for (const route of routes) {
    const pathKey = `${route.method} ${route.path}`;
    if (seenPaths.has(pathKey)) throw new Error(`Duplicate generated route: ${pathKey}`);
    seenPaths.add(pathKey);

    if (seenOperationIds.has(route.operationId)) {
      throw new Error(`Duplicate generated operation id: ${route.operationId}`);
    }
    seenOperationIds.add(route.operationId);
  }
}

function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const header = `// AUTO-GENERATED by server/scripts/generate-api-client.ts — do not edit.
// Run \`bun run api:generate\` from the server directory after changing routes.
`;

/** Builds the exact browser-client source consumed by src/lib/api/index.ts. */
export function buildClientSource(version: string, routes: readonly GeneratedRoute[]): string {
  validateRoutes(routes);

  const routesLiteral = routes
    .map((route) => `  {\n    method: ${quote(route.method)},\n    path: ${quote(route.path)},\n    operationId: ${quote(route.operationId)},\n  }`)
    .join(',\n');

  const pathsLiteral = routes
    .map((route) => `  ${route.operationId}: ${quote(route.path)}`)
    .join(',\n');

  const body = `export const API_VERSION = ${quote(version)} as const;

export const API_ROUTES = [
${routesLiteral},
] as const;

/** Typed path templates keyed by generated operation id. */
export const API_PATHS = {
${pathsLiteral},
} as const;

export type ApiRoute = (typeof API_ROUTES)[number];
export type ApiPath = (typeof API_PATHS)[keyof typeof API_PATHS];

/** Resolves path parameters and an optional query string from a generated template. */
export function apiPath(
  path: ApiPath,
  params: Record<string, string | number> = {},
  query?: string | URLSearchParams,
): string {
  let resolved: string = path;
  for (const [name, value] of Object.entries(params)) {
    resolved = resolved.replace(\`:\${name}\`, encodeURIComponent(String(value)));
  }

  const search = typeof query === 'string'
    ? query.replace(/^\\?/, '')
    : query?.toString();
  return search ? \`\${resolved}?\${search}\` : resolved;
}
`;

  return `${header}${body}`;
}

export function main(): void {
  const version = readApiVersion(readFileSync(versionUrl, 'utf8'));
  const routes = extractRoutes(readFileSync(routerUrl, 'utf8'), version);
  const output = buildClientSource(version, routes);

  let current: string | null;
  try {
    current = readFileSync(outputUrl, 'utf8');
  } catch {
    current = null;
  }

  if (checkOnly) {
    if (current !== output) {
      console.error('Generated API client is stale. Run `bun run api:generate`.');
      process.exit(1);
    }
    console.log(`Generated API client is current (${routes.length} routes).`);
  } else {
    mkdirSync(new URL('./', outputUrl), { recursive: true });
    writeFileSync(outputUrl, output);
    console.log(`Wrote ${routes.length} routes to src/lib/api/generated/routes.ts`);
  }
}

if (import.meta.main) main();
