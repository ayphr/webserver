import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const routerSource = readFileSync(new URL('server/src/api/router.ts', root), 'utf8');
const versionSource = readFileSync(new URL('server/src/api/version.ts', root), 'utf8');
const outputUrl = new URL('src/lib/api/generated/routes.ts', root);
const checkOnly = process.argv.includes('--check');

const version = versionSource.match(/API_VERSION\s*=\s*'([^']+)'/)?.[1];
if (!version) throw new Error('Could not read API_VERSION from server/src/api/version.ts');

const routePattern = /\{\s*method:\s*'([A-Z]+)',\s*path:\s*'([^']+)'/g;
const routes = [...routerSource.matchAll(routePattern)].map((match) => {
  const method = match[1] ?? '';
  const path = match[2] ?? '';
  const unversionedPath = path === '/api'
    ? '/api'
    : path.startsWith('/api/')
      ? path
      : `/api${path.startsWith('/') ? path : `/${path}`}`;
  return {
    method,
    path: `/api/${version}${unversionedPath.slice('/api'.length)}`,
    operationId: operationId(method, unversionedPath),
  };
});

if (routes.length === 0) throw new Error('No routes found in server/src/api/router.ts');

const seenPaths = new Set<string>();
for (const route of routes) {
  if (seenPaths.has(`${route.method} ${route.path}`)) {
    throw new Error(`Duplicate generated route: ${route.method} ${route.path}`);
  }
  seenPaths.add(`${route.method} ${route.path}`);
}

function operationId(method: string, path: string): string {
  const parts = path
    .replace(/^\/api\//, '')
    .split('/')
    .flatMap((part) => part.split(/[^A-Za-z0-9]+/).filter(Boolean))
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1));
  return [method.toLowerCase(), ...parts].join('');
}

const header = `// AUTO-GENERATED by server/scripts/generate-api-client.ts — do not edit.
// Run \`bun run api:generate\` from the server directory after changing routes.
`;

function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const routesLiteral = routes
  .map((route) => `  {\n    method: ${quote(route.method)},\n    path: ${quote(route.path)},\n    operationId: ${quote(route.operationId)},\n  }`)
  .join(',\n');

const pathsLiteral = routes
  .map((route) => `  ${route.operationId}: ${quote(route.path)}`)
  .join(',\n');

const body = `export const API_VERSION = ${quote(version)} as const;

export const API_ROUTES = [
${routesLiteral},
] as const;

/** Typed path templates keyed by generated operation id. */
export const API_PATHS = {
${pathsLiteral},
} as const;

export type ApiRoute = (typeof API_ROUTES)[number];
export type ApiPath = (typeof API_PATHS)[keyof typeof API_PATHS];

/** Resolves path parameters and an optional query string from a generated template. */
export function apiPath(
  path: ApiPath,
  params: Record<string, string | number> = {},
  query?: string | URLSearchParams,
): string {
  let resolved: string = path;
  for (const [name, value] of Object.entries(params)) {
    resolved = resolved.replace(\`:\${name}\`, encodeURIComponent(String(value)));
  }

  const search = typeof query === 'string'
    ? query.replace(/^\\?/, '')
    : query?.toString();
  return search ? \`\${resolved}?\${search}\` : resolved;
}
`;

const output = `${header}${body}`;
const current = (() => {
  try {
    return readFileSync(outputUrl, 'utf8');
  } catch {
    return null;
  }
})();

if (checkOnly) {
  if (current !== output) {
    console.error('Generated API client is stale. Run `bun run api:generate`.');
    process.exit(1);
  }
  console.log(`Generated API client is current (${routes.length} routes).`);
} else {
  mkdirSync(new URL('./', outputUrl), { recursive: true });
  writeFileSync(outputUrl, output);
  console.log(`Wrote ${routes.length} routes to src/lib/api/generated/routes.ts`);
}
